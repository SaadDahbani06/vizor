"""End-to-end U.S. small-business demos: internal data + real external observations -> decision.

  python -m decisiondesk.us_demo restaurant --state TX --confirm
  python -m decisiondesk.us_demo retail --store <store_no> --max-reserve 40000 --confirm

Restaurant: the business records are SYNTHETIC (no real individual restaurant history is
available); the external observations are REAL (FRED point-in-time, Kwick365 aggregate
benchmarks). Retail: the business records are REAL store-level PURCHASES from Iowa dataset 1051
(requires the official export on disk); customer demand and inventory are NOT observed, so only
procurement-budget decisions are evaluated. Every recommendation comes from the Milestone 3
quantitative engine; nothing is generated by a language model.
"""
