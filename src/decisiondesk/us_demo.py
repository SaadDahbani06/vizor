KWICK_CITATION = "Kwick365 — The Independent Restaurant Index, https://kwick365.com"


def _print_profile(profile: BusinessProfile, frame: pd.DataFrame, analyses: tuple[str, ...]):
    print(f"\n== Business profile (confirmed by user: {profile.confirmed_by_user}) ==")
    print(f"   {profile.business_name} | industry={profile.industry} | state={profile.state} | "
          f"objective={profile.objective} | constraints={profile.constraints}")
    cap = capabilities(frame, profile)
    print(f"   uploaded roles: {cap.roles_present}; {cap.days} days")
    for name, desc in cap.supported.items():
        print(f"   SUPPORTED   {name}: {desc}")
    for name, why in cap.unsupported.items():
        print(f"   UNSUPPORTED {name}: {why}")
    for n in cap.notes:
        print(f"   note: {n}")
    print("\n== Source selection (relevance to industry + analysis; status is literal) ==")
    for s in select_sources(profile.industry, analyses):
        print(f"   {s['key']:12s} {s['status']:28s} usable_now={s['usable_now']!s:5s} for "
              f"{s['for']} | caveat: {s['caveat']}")
    return cap


def _print_obs(obs: list[ExternalObservation]) -> None:
    for o in obs:
        print(f"   [{o.data_origin}] {o.source} {o.series_id} ({o.geography}) "
              f"{o.observed_at} = {fmt_num(o.value)} {o.units}; available {o.available_at}; "
              f"freshness {o.freshness_days} d; vintage {o.vintage_mode}")


def restaurant(state: str, confirm: bool, starting_cash: float | None, sims: int) -> None:
    profile = BusinessProfile("Demo independent restaurant (SYNTHETIC records)", "restaurant",
                              state, Objective.MAX_EXPECTED_PROFIT.value,
                              {"max_price_increase": 0.05, "implementation_budget_usd": 1000},
                              confirmed_by_user=confirm)
    profile.require_confirmation()
    kw = Kwick365Connector(cache_first=True)
    orders, _oprov = kw.fetch("online-orders-per-store", "us")
    seg, _seg_rep = contiguous_daily(orders)
    origin = seg["date"].max()

    # 1. Internal indicators: synthetic records re-dated to end on the benchmark's last stable day,
    #    so every external observation below is "as of" the same date (no look-ahead).
    history = make_sample("restaurant")
    history["date"] = history["date"] + (origin - history["date"].max())
    history, _ = validate_daily_frame(history, source="synthetic restaurant (re-dated)")
    _print_profile(profile, history, ("benchmark", "cost_inflation", "pricing_context",
                                      "stress_test", "demand_context"))
    tail = history.tail(28)
    print(f"\n== 1. Internal indicators (SYNTHETIC business records, re-dated to end {origin.date()}) ==")
    print(f"   last 28 days: revenue ${tail.revenue.sum():,.0f}; variable costs "
          f"${tail.variable_costs.sum():,.0f} ({tail.variable_costs.sum() / tail.revenue.sum():.1%} "
          f"of revenue); average ticket ${tail.revenue.sum() / tail.units_sold.sum():.2f}")

    # 2. External observations as of the origin.
    obs = []
    fred = FREDConnector(offline=True)
    for sid, geo in (("CUSR0000SAF11", "US city average"), ("CUSR0000SEFV", "US city average"),
                     ("UNRATE", "United States")):
        v, p = fred.fetch_vintages(sid, "2021-01-01")
        o = fred_observation(v, sid, origin, p.units, geo, p.restrictions)
        if o:
            obs.append(o)
    yoy = {}
    for o in obs:
        v, _ = fred.fetch_vintages(o.series_id, "2021-01-01")
        snap = v[(v.realtime_start <= origin) & (v.realtime_end >= origin)].set_index("observed_at").value
        from .macro import _latest_comparable
        last = _latest_comparable(snap, pd.DateOffset(years=1))
        prev = snap[last - pd.DateOffset(years=1)]
        yoy[o.series_id] = ((snap[last] - prev) if o.series_id == "UNRATE"
                            else 100 * (snap[last] / prev - 1), last)
    bench = {}
    for reading in ("online-ticket", "instore-ticket", "online-orders-per-store"):
        f, p = kw.fetch(reading, "us")
        s = f[f["stable"]]
        last = s.iloc[-1]
        obs.append(ExternalObservation(
            "Kwick365", reading, "US (KwickPOS independent restaurants)", p.units,
            str(last.day.date()), str((last.day + pd.Timedelta(days=1)).date()), p.retrieved_at_utc,
            float(last.value), "REAL_AGGREGATE_INDUSTRY", p.vintage_mode, p.restrictions,
            int((origin - last.day).days)))
        first28, last28 = s.head(28), s.tail(28)
        bench[reading] = {"first": float(first28.value.mean()), "last": float(last28.value.mean()),
                          "first_span": (first28.day.min().date(), first28.day.max().date()),
                          "last_span": (last28.day.min().date(), last28.day.max().date()),
                          "n_stores": int(last.n_stores), "n": int(last.n), "date": last.day.date()}
    print("\n== 2. External observations (as of the forecast origin) ==")
    _print_obs(obs)
    for sid, (val, when) in yoy.items():
        print(f"   FRED {sid}: 12-month change {val:+.2f}{' pp' if sid == 'UNRATE' else '%'} for "
              f"{when:%Y-%m} (latest month with a published comparison; October 2025 was never "
              "published)")
    for r, b in bench.items():
        print(f"   Kwick365 {r}: mean of published days {b['last_span'][0]}..{b['last_span'][1]} = "
              f"{b['last']:.2f} vs {b['first']:.2f} for {b['first_span'][0]}..{b['first_span'][1]} "
              f"({b['last'] / b['first'] - 1:+.1%}); latest day {b['date']}: n = {b['n_stores']} "
              f"restaurants, {b['n']} orders. Cite: {KWICK_CITATION}")

    # 3. Forecast the benchmark with the validation-selected model (real aggregate data).
    target = "online_orders_per_store"
    bhist = seg.rename(columns={"value": target})[["date", target]]
    board = build_leaderboard(bhist, target, dataset="kwick365_us", data_label="REAL AGGREGATE",
                              cfg=SHORT_CFG)
    fc = forecast_selected(bhist, target, board)
    sel = next(m for m in board.models if m.name == board.selected)
    change = fc[target].mean() / bhist[target].tail(14).mean() - 1
    print(f"\n== 3. Forecasts ==\n   Benchmark (REAL aggregate): {board.selected} forecasts online orders "
          f"per restaurant {change:+.1%} for the next 14 days vs the last 14 published days "
          f"(untouched-test WAPE {sel.holdout['wape']:.3f}, 80% interval coverage "
          f"{sel.holdout_interval_coverage:.0%}: {'LOW reliability' if sel.holdout_interval_coverage < 0.7 else 'adequate'}).")
    print("   Business (SYNTHETIC): selected models per target are listed in section 1 of the "
          "decision report below.")

    # 4-7. Exposure -> actions -> outcomes -> explanation (Milestone 3 engine).
    fafh = yoy.get("CUSR0000SEFV", (None,))[0]
    food = yoy.get("CUSR0000SAF11", (None,))[0]
    prices = tuple(sorted({0.03, float(round(max(fafh or 0, 0) / 100, 3)), 0.08}))
    cfg = RestaurantDecisionConfig(price_increases=prices)
    print(f"\n== 4. External change / exposure ==\n   Input costs: food-at-home CPI {food:+.2f}% YoY "
          f"(observed). Menu-price inflation: food-away-from-home CPI {fafh:+.2f}% YoY (observed); "
          f"a price action sized to it ({prices}) is added as a candidate.\n   The decision report's "
          "stress test applies the food-at-home change to variable costs (HYPOTHETICAL pass-through).")
    cash = StartingCash(starting_cash, "declared by user", True) if starting_cash is not None else None
    ctx = OrganizationContext(profile.business_name, "restaurant", "SYNTHETIC", starting_cash=cash)
    run = run_restaurant(history, ctx, Objective.MAX_EXPECTED_PROFIT,
                         dataset="restaurant_SYNTHETIC_redated", cfg=cfg, n_sims=sims)
    print("\n== 5-7. Actions, outcomes, ranking and explanation (Milestone 3 engine) ==")
    print_run(run)

    # Benchmark-demand stress: hypothetical only (no relationship to this restaurant is estimated).
    sb = stressed(run.bundle, {"revenue": 1 + change, "variable_costs": 1 + change})
    from .decision.restaurant import UNITS, simulate_restaurant
    draws = make_draws(run.bundle, sims)
    souts = evaluate_actions(run.actions, lambda a, d: simulate_restaurant(sb, a, d, cash),
                             draws, cfg.constraints, UNITS)
    srec = rank(souts, Objective.MAX_EXPECTED_PROFIT, horizon_days=run.bundle.horizon, evidence={})
    print(f"\n   HYPOTHETICAL benchmark stress: if this restaurant's sales moved like the benchmark "
          f"forecast ({change:+.1%}), the engine would recommend {srec.recommended_action_id} "
          f"({srec.strength}). No link between this restaurant and the benchmark is estimated.")


def retail(store: str | None, data_dir: str, confirm: bool, max_reserve: float | None,
           sims: int) -> None:
    profile = BusinessProfile(f"Iowa Class E liquor licensee {store or '(not selected)'}",
                              "retail", "IA", Objective.MIN_CASH_SHORTAGE_RISK.value,
                              {"max_purchasing_reserve_usd": max_reserve},
                              confirmed_by_user=confirm)
    profile.require_confirmation()
    files = export_files(data_dir)
    if not files or not store:
        print("BLOCKED: real store purchase data is required for this demo.")
        print(f"  * Download the official export of https://data.iowa.gov/catalog/dataset/1051 "
              f"(Download -> Download as CSV) into {data_dir}/ (gitignored).")
        print("  * Then: python -m decisiondesk.us_validation iowa --scan   # pick a suitable store")
        print("  * Then: python -m decisiondesk.us_demo retail --store <store_no> --max-reserve "
              "<USD> --confirm")
        print("\nCapability check from the dataset-1051 SCHEMA only (no rows loaded; the day "
              "count below is a placeholder meeting the 504-day minimum):")
        schema = pd.DataFrame({"date": pd.date_range("2020-01-01", periods=504),
                               "purchase_dollars": 0.0})
        _print_profile(profile, schema, ("procurement_forecast", "procurement_budget",
                                         "stress_test"))
        return
    daily, report, prov = store_daily(files, store)
    hist = daily[["date", "purchase_dollars"]]
    _print_profile(profile, hist, ("procurement_forecast", "procurement_budget", "stress_test"))
    print(f"\n== 1. Internal indicators (REAL store PURCHASES; {prov.restrictions}) ==")
    print(f"   store {report.store_no}: {report.names} | {report.cities} | {report.first_date}.."
          f"{report.last_date} | suitable={report.suitable} {report.reasons}")
    ctx = OrganizationContext(profile.business_name, "retail", "REAL STORE PURCHASES")
    inv = run_retail(daily.rename(columns={"purchase_dollars": "revenue"}).assign(
        variable_costs=0.0), ctx, Objective.MAX_EXPECTED_PROFIT, dataset="iowa")
    print(f"   inventory-policy decisions: UNSUPPORTED ({inv.unsupported.reason})")
    bundle = build_forecast_bundle(hist, ("purchase_dollars",), dataset=f"iowa_{store}",
                                   data_label="REAL STORE PURCHASES")
    tf = bundle.targets["purchase_dollars"]
    print(f"\n== 3. Procurement forecast: {tf.model} (val WAPE {tf.validation_wape:.3f}, test WAPE "
          f"{tf.test_wape:.3f}); next {bundle.horizon} days ${tf.point.sum():,.0f} ==")
    fred = FREDConnector(offline=True)
    v, p = fred.fetch_vintages("CUSR0000SAF116", "2021-01-01")
    o = fred_observation(v, "CUSR0000SAF116", bundle.origin_date, p.units, "US city average",
                         p.restrictions)
    snap = v[(v.realtime_start <= bundle.origin_date) & (v.realtime_end >= bundle.origin_date)]
    snap = snap.set_index("observed_at").value
    from .macro import _latest_comparable
    last = _latest_comparable(snap, pd.DateOffset(years=1))
    alc = snap[last] / snap[last - pd.DateOffset(years=1)] - 1
    print("\n== 2/4. External observation and exposure ==")
    _print_obs([o])
    print(f"   CPI alcoholic beverages {alc:+.2%} YoY ({last:%Y-%m}); used ONLY as a hypothetical "
          "wholesale price change in the stress test.")
    cons = (Constraint("cash available for purchasing", "metric:reserved_cash:mean", "max",
                       max_reserve, "USD"),) if max_reserve else ()
    cfg = ProcurementConfig(constraints=cons)
    actions, _levels = procurement_actions(bundle, hist, cfg)
    draws = make_draws(bundle, sims)

    def sim(a, d, b=bundle):
        return simulate_procurement(b, a, d)

    outs = evaluate_actions(actions, sim, draws, cons, PROC_UNITS)
    rec = rank(outs, Objective.MIN_CASH_SHORTAGE_RISK, horizon_days=bundle.horizon, evidence={})
    print("\n== 5-7. Procurement reserve options (objective: minimize P(reserve overrun)) ==")
    for r in rec.ranking:
        o_ = next(x for x in outs if x.action.action_id == r.action_id)
        print(f"   {('#' + str(r.rank)) if r.rank else 'excluded':9s} {r.action_id:18s} reserve "
              f"${o_.metrics['reserved_cash'].mean:>9,.0f}  P(overrun) {r.objective_mean:6.1%}  "
              f"E[shortfall] ${o_.metrics['expected_shortfall'].mean:>8,.0f}  E[idle] "
              f"${o_.metrics['idle_cash'].mean:>8,.0f}  {'; '.join(r.violations)}")
    print(f"   RECOMMENDED: {rec.recommended_action_id} ({rec.strength}). {rec.rationale}")
    stress_actions = [replace(a, assumptions=(Assumption("wholesale_price_change", float(alc),
                                                         "fraction", "hypothetical"),))
                      for a in actions]
    srec = rank(evaluate_actions(stress_actions, sim, draws, cons, PROC_UNITS),
                Objective.MIN_CASH_SHORTAGE_RISK, horizon_days=bundle.horizon, evidence={})
    print(f"   HYPOTHETICAL stress (wholesale prices {alc:+.2%}): recommended "
          f"{srec.recommended_action_id} ({srec.strength}).")
    print("   Human approval required; nothing executed. Purchases are not customer demand.")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("restaurant")
    r.add_argument("--state", default="TX")
    r.add_argument("--starting-cash", type=float, default=None)
    r.add_argument("--confirm", action="store_true",
                   help="confirm industry, state, objective and constraints")
    r.add_argument("--sims", type=int, default=4000)
    s = sub.add_parser("retail")
    s.add_argument("--store")
    s.add_argument("--data-dir", default="data/private/iowa_liquor")
    s.add_argument("--max-reserve", type=float, default=None)
    s.add_argument("--confirm", action="store_true")
    s.add_argument("--sims", type=int, default=4000)
    args = parser.parse_args()
    load_dotenv(".env")
    np.seterr(all="ignore")
    if args.cmd == "restaurant":
        restaurant(args.state.upper(), args.confirm, args.starting_cash, args.sims)
    else:
        retail(args.store, args.data_dir, args.confirm, args.max_reserve, args.sims)


if __name__ == "__main__":
    try:
        main()
    except (ConnectorError, ValueError) as exc:
        raise SystemExit(f"error: {exc}")
